// Compute which week the user is in given the due date (ISO string)
export function computeWeek(dueDateISO) {
  if (!dueDateISO) return null;
  const due = new Date(dueDateISO);
  const start = new Date(due);
  start.setDate(start.getDate() - 280); // 40 weeks = 280 days from conception to due date
  const now = new Date();
  const diffDays = Math.floor((now - start) / (1000 * 60 * 60 * 24));
  const week = Math.floor(diffDays / 7) + 1; // 1-indexed
  const dayOfWeek = diffDays % 7;
  const daysUntilDue = Math.ceil((due - now) / (1000 * 60 * 60 * 24));
  return {
    week: Math.max(1, Math.min(42, week)),
    dayOfWeek,
    totalDays: diffDays,
    daysUntilDue,
    isPostTerm: daysUntilDue < 0,
    isTerm: week >= 37,
    trimester: week <= 13 ? 1 : week <= 27 ? 2 : 3,
  };
}

